export const BUTTON_KINDS = [
  "menu",
  "stick",
  "shade",
  "hide",
  "maximize",
  "close",
];
export const TOGGLED_KINDS = ["stick", "shade", "maximize"];
export const BUTTON_STATES = ["active", "inactive", "prelight", "pressed"];

export const GLYPH_FOR = {
  menu: "menu",
  stick: "pin",
  "stick-toggled": "pin-off",
  shade: "chevron-up",
  "shade-toggled": "chevron-down",
  hide: "minus",
  maximize: "square",
  "maximize-toggled": "copy",
  close: "x",
};

export function buttonMatrix() {
  const bases = [
    ...BUTTON_KINDS,
    ...TOGGLED_KINDS.map((kind) => `${kind}-toggled`),
  ];
  const entries = [];
  for (const base of bases) {
    for (const state of BUTTON_STATES) {
      entries.push({
        name: `${base}-${state}`,
        base,
        glyph: GLYPH_FOR[base],
        state,
      });
    }
  }
  return entries;
}

// The title segments and the button slots paint the same 2px row of the
// titlebar, so the edge colour is derived from the same focusEdgeColor
// helper renderTitleXpm and renderTopCornerSvg use — never a second
// ternary that could drift from theirs.
export function buttonStateColors(flavorBlock, accentHex, state) {
  const { surface, text } = flavorBlock;
  const sunk = surface.bg_sunk;

  switch (state) {
    case "active":
      return {
        backing: null,
        glyph: text.fg_muted,
        edge: focusEdgeColor(flavorBlock, accentHex, true),
      };
    case "inactive":
      return {
        backing: null,
        glyph: text.fg_muted,
        edge: focusEdgeColor(flavorBlock, accentHex, false),
      };
    case "prelight":
      return {
        backing: composite(sunk, flavorBlock.state.hover),
        glyph: text.fg,
        edge: focusEdgeColor(flavorBlock, accentHex, true),
      };
    case "pressed":
      return {
        backing: composite(sunk, flavorBlock.state.active),
        glyph: text.fg,
        edge: focusEdgeColor(flavorBlock, accentHex, true),
      };
    default:
      throw new Error(`Unknown button state: ${state}`);
  }
}

// The button slots, the title segments and the top corners all paint the
// same 32px bar and the same 2px focus edge along its bottom. They must
// derive that geometry from one place or the edge steps at each button.
const TITLEBAR_HEIGHT = 32;
const FOCUS_EDGE_HEIGHT = 2;
const CORNER_RADIUS = 8;
const BOTTOM_CORNER_SIZE = 16;

const BUTTON_WIDTH = 24;
const BUTTON_HEIGHT = TITLEBAR_HEIGHT;
const BUTTON_CELL = 24;
const BUTTON_CELL_Y = (BUTTON_HEIGHT - BUTTON_CELL) / 2;
const GLYPH_BOX = 16;
const GLYPH_OFFSET = BUTTON_CELL_Y + (BUTTON_CELL - GLYPH_BOX) / 2;

export function renderButtonSvg({
  flavorBlock,
  accentHex,
  glyphMarkup,
  state,
}) {
  const colors = buttonStateColors(flavorBlock, accentHex, state);
  const backing =
    colors.backing === null
      ? ""
      : `  <rect y="${BUTTON_CELL_Y}" width="${BUTTON_CELL}" height="${BUTTON_CELL}" rx="8" fill="${colors.backing}"/>\n`;

  // Lucide is authored at stroke-width 2 on a 24 grid. Scaling to the
  // 16px glyph box (16/24) with stroke-width 2.25 rasterises at 1.5px.
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${BUTTON_WIDTH}" height="${BUTTON_HEIGHT}" viewBox="0 0 ${BUTTON_WIDTH} ${BUTTON_HEIGHT}">
  <rect width="${BUTTON_WIDTH}" height="${BUTTON_HEIGHT}" fill="${flavorBlock.surface.bg_sunk}"/>
  <rect y="${BUTTON_HEIGHT - FOCUS_EDGE_HEIGHT}" width="${BUTTON_WIDTH}" height="${FOCUS_EDGE_HEIGHT}" fill="${colors.edge}"/>
${backing}  <g transform="translate(4,${GLYPH_OFFSET}) scale(0.66667)" fill="none" stroke="${colors.glyph}" stroke-width="2.25" stroke-linecap="round" stroke-linejoin="round">${glyphMarkup}</g>
</svg>
`;
}

export const TITLE_SEGMENTS = [1, 2, 3, 4, 5];
export const EDGES = ["left", "right", "bottom"];

function focusEdgeColor(flavorBlock, accentHex, active) {
  return active ? accentHex : flavorBlock.border.subtle;
}

export function renderTitleXpm({ flavorBlock, accentHex, active, segment }) {
  const fill = flavorBlock.surface.bg_sunk;
  const edge = focusEdgeColor(flavorBlock, accentHex, active);
  const rows = [];
  for (let y = 0; y < TITLEBAR_HEIGHT; y += 1) {
    rows.push(y < TITLEBAR_HEIGHT - FOCUS_EDGE_HEIGHT ? "aa" : "bb");
  }
  const name = `title_${segment}_${active ? "active" : "inactive"}`;
  return renderXpm(name, rows, { a: fill, b: edge });
}

export function renderEdgeXpm({ flavorBlock, edge, active }) {
  const name = `${edge.replace(/-/g, "_")}_${active ? "active" : "inactive"}`;
  return renderXpm(name, ["a"], { a: flavorBlock.border.default });
}

export function renderTopCornerSvg({ flavorBlock, accentHex, side, active }) {
  if (side !== "left" && side !== "right") {
    throw new Error(`Unknown side: ${side}`);
  }
  const fill = flavorBlock.surface.bg_sunk;
  const edge = focusEdgeColor(flavorBlock, accentHex, active);
  const w = CORNER_RADIUS;
  const h = TITLEBAR_HEIGHT;
  const edgeY = h - FOCUS_EDGE_HEIGHT;

  // Drawn as the left-hand corner, then mirrored for the right.
  const body = `<path d="M ${w} 0 L ${w} ${h} L 0 ${h} L 0 ${CORNER_RADIUS} A ${CORNER_RADIUS} ${CORNER_RADIUS} 0 0 1 ${CORNER_RADIUS} 0 Z" fill="${fill}"/>
    <rect x="0" y="${edgeY}" width="${w}" height="${FOCUS_EDGE_HEIGHT}" fill="${edge}"/>`;
  const wrapped =
    side === "left"
      ? body
      : `<g transform="translate(${w},0) scale(-1,1)">${body}</g>`;

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
    ${wrapped}
</svg>
`;
}

export function renderBottomCornerSvg({ flavorBlock, side }) {
  if (side !== "left" && side !== "right") {
    throw new Error(`Unknown side: ${side}`);
  }
  const border = flavorBlock.border.default;
  const s = BOTTOM_CORNER_SIZE;

  // A 1px run along the outer vertical edge and along the bottom. The
  // asset is 16x16 so the corner-resize grab region is 16px; everything
  // outside the two 1px strips stays transparent.
  const body = `<rect x="0" y="0" width="1" height="${s}" fill="${border}"/>
    <rect x="0" y="${s - 1}" width="${s}" height="1" fill="${border}"/>`;
  const wrapped =
    side === "left"
      ? body
      : `<g transform="translate(${s},0) scale(-1,1)">${body}</g>`;

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${s}" height="${s}" viewBox="0 0 ${s} ${s}">
    ${wrapped}
</svg>
`;
}
